-- =============================================================================
-- ShopMetric - one-time Snowflake setup. Run in a Snowsight worksheet as ACCOUNTADMIN.
-- Replace <PUBLIC_KEY> with the body of secrets/snowflake_rsa_key.pub (no BEGIN/END lines).
-- The pipeline creates its own tables on first start (python -m shopmetric.init_infra).
-- =============================================================================
USE ROLE ACCOUNTADMIN;

-- Compute: the smallest warehouse, suspended after 60 s idle -> you pay only while it works.
CREATE WAREHOUSE IF NOT EXISTS SHOPMETRIC_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- Guard rail for trial credits: notify at 80%, suspend the warehouse at 100%.
CREATE RESOURCE MONITOR IF NOT EXISTS SHOPMETRIC_RM
  WITH CREDIT_QUOTA = 20 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE SHOPMETRIC_WH SET RESOURCE_MONITOR = SHOPMETRIC_RM;

CREATE DATABASE IF NOT EXISTS SHOPMETRIC;
CREATE SCHEMA IF NOT EXISTS SHOPMETRIC.ANALYTICS;

-- Least privilege: the pipeline writes, the dashboard / AI copilot only reads.
CREATE ROLE IF NOT EXISTS SHOPMETRIC_WRITER;
CREATE ROLE IF NOT EXISTS SHOPMETRIC_READER;
GRANT ROLE SHOPMETRIC_WRITER TO ROLE SYSADMIN;
GRANT ROLE SHOPMETRIC_READER TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE SHOPMETRIC_WH TO ROLE SHOPMETRIC_WRITER;
GRANT USAGE ON WAREHOUSE SHOPMETRIC_WH TO ROLE SHOPMETRIC_READER;
GRANT USAGE ON DATABASE SHOPMETRIC TO ROLE SHOPMETRIC_WRITER;
GRANT USAGE ON DATABASE SHOPMETRIC TO ROLE SHOPMETRIC_READER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT
  ON SCHEMA SHOPMETRIC.ANALYTICS TO ROLE SHOPMETRIC_WRITER;
GRANT USAGE ON SCHEMA SHOPMETRIC.ANALYTICS TO ROLE SHOPMETRIC_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SHOPMETRIC.ANALYTICS TO ROLE SHOPMETRIC_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA SHOPMETRIC.ANALYTICS TO ROLE SHOPMETRIC_READER;

-- Service user: key-pair auth only. Snowflake is retiring password sign-in for service users,
-- so a TYPE = SERVICE user with an RSA key is the supported way for pipelines to connect.
CREATE USER IF NOT EXISTS SHOPMETRIC_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = SHOPMETRIC_WRITER
  DEFAULT_WAREHOUSE = SHOPMETRIC_WH
  DEFAULT_NAMESPACE = SHOPMETRIC.ANALYTICS
  RSA_PUBLIC_KEY = '<PUBLIC_KEY>';
GRANT ROLE SHOPMETRIC_WRITER TO USER SHOPMETRIC_SVC;
GRANT ROLE SHOPMETRIC_READER TO USER SHOPMETRIC_SVC;

